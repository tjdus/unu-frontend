export type PolicyBlock =
  | { type: "p"; text: string }
  | { type: "note"; text: string }
  | { type: "ol"; items: string[] }
  | { type: "kv"; rows: [string, string][] }
  | { type: "table"; head: string[]; rows: string[][] }
  | { type: "sub"; title: string; blocks: PolicyBlock[] };

export type PolicyArticle = { id: string; nav: string; title: string; blocks: PolicyBlock[] };

const p = (text: string): PolicyBlock => ({ type: "p", text });
const note = (text: string): PolicyBlock => ({ type: "note", text });
const ol = (...items: string[]): PolicyBlock => ({ type: "ol", items });
const kv = (...rows: [string, string][]): PolicyBlock => ({ type: "kv", rows });
const sub = (title: string, ...blocks: PolicyBlock[]): PolicyBlock => ({ type: "sub", title, blocks });
const table = (head: string[], ...rows: string[][]): PolicyBlock => ({ type: "table", head, rows });

